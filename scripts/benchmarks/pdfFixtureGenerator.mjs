import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createBenchmarkPdf } from './generate-large-pdf.mjs';

const FIXTURE_DEFINITIONS = [
  { name: 'small', pageCount: 1 },
  { name: 'large-100', pageCount: 100 },
  { name: 'large-1000', pageCount: 1000 },
  {
    name: 'varied-sizes',
    pageCount: 4,
    pageSizeForPage: (page) => [[612, 792], [792, 612], [360, 540], [1000, 500]][page - 1],
  },
];

const hash = (buffer) => crypto.createHash('sha256').update(buffer).digest('hex');

function buildManifest(fixtures) {
  return { schemaVersion: 1, totalBytes: fixtures.reduce((total, fixture) => total + fixture.byteLength, 0), fixtures };
}

export function renderFixtureRegistry() {
  return `// Generated by scripts/benchmarks/generate-mobile-pdf-fixtures.mjs. Do not edit.\n` +
    `declare const require: (path: string) => number;\n\n` +
    `export const mobileFixtureRegistry = {\n` +
    FIXTURE_DEFINITIONS.map(({ name }) => `  ${JSON.stringify(name)}: require("./assets/fixtures/${name}.pdf"),`).join('\n') +
    `\n} as const;\n`;
}

export async function generateMobileFixtures(outputDir) {
  const fixturesDir = path.join(outputDir, 'assets', 'fixtures');
  await fs.mkdir(fixturesDir, { recursive: true });
  const fixtures = [];

  for (const definition of FIXTURE_DEFINITIONS) {
    const buffer = createBenchmarkPdf(definition);
    const outputPath = path.join(fixturesDir, `${definition.name}.pdf`);
    await fs.writeFile(outputPath, buffer);
    fixtures.push({ name: definition.name, file: `assets/fixtures/${definition.name}.pdf`, sha256: hash(buffer), byteLength: buffer.byteLength, pageCount: definition.pageCount });
  }

  const manifest = buildManifest(fixtures);
  await fs.writeFile(path.join(fixturesDir, 'fixture-manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
  await fs.writeFile(path.join(outputDir, 'fixtureRegistry.generated.ts'), renderFixtureRegistry());
  return manifest;
}

export async function verifyMobileFixtures(outputDir) {
  const manifest = JSON.parse(await fs.readFile(path.join(outputDir, 'assets', 'fixtures', 'fixture-manifest.json'), 'utf8'));
  const actual = [];
  for (const expected of manifest.fixtures) {
    const buffer = await fs.readFile(path.join(outputDir, expected.file));
    const current = { name: expected.name, file: expected.file, sha256: hash(buffer), byteLength: buffer.byteLength, pageCount: expected.pageCount };
    if (current.sha256 !== expected.sha256 || current.byteLength !== expected.byteLength) throw new Error(`fixture mismatch: ${expected.name}`);
    actual.push(current);
  }
  const verified = buildManifest(actual);
  if (verified.totalBytes !== manifest.totalBytes) throw new Error('fixture manifest total mismatch');
  return manifest;
}
